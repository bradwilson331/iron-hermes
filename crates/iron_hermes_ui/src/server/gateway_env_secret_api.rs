    #[test]
    fn root_scope_write_creates_key_single_quoted_at_0600_and_preserves_existing_key() {
        use std::os::unix::fs::PermissionsExt;

        let _g = crate::server::test_support::env_lock();
        let home_dir = tempfile::tempdir().expect("tempdir");
        unsafe { std::env::set_var("IRONHERMES_HOME", home_dir.path()) };

        seeded_config(true).save().expect("seed root config.yaml");

        // Pre-existing unrelated key must survive the write untouched.
        let env_path = ironhermes_core::config::Config::env_path();
        let pre_existing = vec![("UNRELATED_KEY".to_string(), "keep-me".to_string())];
        let pre_contents =
            render_root_env_with_stamp("root", &pre_existing).expect("render pre-existing .env");
        crate::server::profile_api::write_env_atomic_0600(&env_path, &pre_contents)
            .expect("seed pre-existing .env");

        let secret = SecretString::from("s3cr3t-val".to_string());
        let result = set_gateway_secret_impl(
            &ConfigScope::Root,
            "IRONHERMES_API_SERVER_KEY",
            &secret,
        );

        let raw = std::fs::read_to_string(&env_path).expect("read written .env");
        let meta = std::fs::metadata(&env_path).expect("stat written .env");
        let env_map =
            crate::server::profile_api::read_env_keys(&env_path).expect("parse written .env");
        unsafe { std::env::remove_var("IRONHERMES_HOME") };

        let ack = result.expect("root-scope write must succeed");
        assert_eq!(ack.key_name, "IRONHERMES_API_SERVER_KEY");
        assert!(ack.present);
        assert!(
            raw.contains("IRONHERMES_API_SERVER_KEY='s3cr3t-val'"),
            "value must be written single-quoted; got:\n{raw}"
        );
        assert_eq!(
            meta.permissions().mode() & 0o777,
            0o600,
            "written .env must be mode 0600"
        );
        assert_eq!(
            env_map.get("UNRELATED_KEY").map(String::as_str),
            Some("keep-me"),
            "a pre-existing unrelated key must survive the write"
        );
    }

