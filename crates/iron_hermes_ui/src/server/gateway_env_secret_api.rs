    #[test]
    fn env_name_injection_is_rejected_before_any_write() {
        let _g = crate::server::test_support::env_lock();
        let home_dir = tempfile::tempdir().expect("tempdir");
        unsafe { std::env::set_var("IRONHERMES_HOME", home_dir.path()) };

        seeded_config(true).save().expect("seed root config.yaml");
        let env_path = ironhermes_core::config::Config::env_path();
        assert!(!env_path.exists(), "no .env must exist before either rejected write");

        let secret = SecretString::from("value".to_string());

        // A newline-bearing name could otherwise forge a second VAR=value
        // line (T-49.3-02-01).
        let newline_result =
            set_gateway_secret_impl(&ConfigScope::Root, "FOO\nBAR", &secret);
        assert!(
            newline_result.is_err(),
            "a newline-bearing key name must be rejected"
        );
        assert!(
            !env_path.exists(),
            "a rejected newline-bearing name must never touch the .env file"
        );

        // A lowercase name is also rejected by validate_key_name's
        // [A-Z][A-Z0-9_]* rule.
        let lowercase_result = set_gateway_secret_impl(&ConfigScope::Root, "foo", &secret);
        unsafe { std::env::remove_var("IRONHERMES_HOME") };

        assert!(
            lowercase_result.is_err(),
            "a lowercase key name must be rejected"
        );
        assert!(
            !env_path.exists(),
            "a rejected lowercase name must never touch the .env file"
        );
    }

    #[test]
    fn value_containing_dollar_brace_quote_and_trailing_backslash_round_trips_literally() {
        let _g = crate::server::test_support::env_lock();
        let home_dir = tempfile::tempdir().expect("tempdir");
        unsafe { std::env::set_var("IRONHERMES_HOME", home_dir.path()) };

        seeded_config(true).save().expect("seed root config.yaml");

        // Exercises dollar-substitution suppression, an embedded single
        // quote, and a trailing backslash (the two-stage dotenvy
        // parser/writer boundary from project memory) in one value.
        const ADVERSARIAL_VALUE: &str = r"${HOME}/it's-mine\";
        let secret = SecretString::from(ADVERSARIAL_VALUE.to_string());
        let result = set_gateway_secret_impl(&ConfigScope::Root, "ADVERSARIAL_KEY", &secret);

        let env_path = ironhermes_core::config::Config::env_path();
        let env_map =
            crate::server::profile_api::read_env_keys(&env_path).expect("parse written .env");
        unsafe { std::env::remove_var("IRONHERMES_HOME") };

        result.expect("adversarial value write must succeed");
        assert_eq!(
            env_map.get("ADVERSARIAL_KEY").map(String::as_str),
            Some(ADVERSARIAL_VALUE),
            "the exact literal must round-trip — no ${{}} substitution, no merged line"
        );
    }

    #[test]
    fn write_refuses_when_gate_closed_before_touching_the_env_file() {
        let _g = crate::server::test_support::env_lock();
        let home_dir = tempfile::tempdir().expect("tempdir");
        unsafe { std::env::set_var("IRONHERMES_HOME", home_dir.path()) };

        seeded_config(false).save().expect("seed root config.yaml with writes disabled");
        let env_path = ironhermes_core::config::Config::env_path();
        assert!(!env_path.exists(), "no .env must exist before the refused write");

        let secret = SecretString::from("value".to_string());
        let result = set_gateway_secret_impl(&ConfigScope::Root, "IRONHERMES_API_SERVER_KEY", &secret);
        let exists_after = env_path.exists();
        unsafe { std::env::remove_var("IRONHERMES_HOME") };

        assert!(result.is_err(), "write must be refused when the gate is closed");
        assert!(!exists_after, "a refused write must never create the .env file");
    }

