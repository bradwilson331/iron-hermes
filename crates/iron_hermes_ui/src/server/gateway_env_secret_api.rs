    #[test]
    fn profile_scope_write_delegates_and_leaves_root_env_untouched() {
        let _g = crate::server::test_support::env_lock();
        let home_dir = tempfile::tempdir().expect("tempdir");
        unsafe { std::env::set_var("IRONHERMES_HOME", home_dir.path()) };

        seeded_config(true).save().expect("seed root config.yaml");
        std::fs::create_dir_all(crate::server::profile_api::profile_dir_for("bot-profile"))
            .expect("create profile dir");

        let root_env_path = ironhermes_core::config::Config::env_path();
        assert!(
            !root_env_path.exists(),
            "root .env must not exist before the profile-scope write"
        );

        let secret = SecretString::from("tg-bot-token".to_string());
        let result = set_gateway_secret_impl(
            &ConfigScope::Profile("bot-profile".to_string()),
            "TELEGRAM_BOT_TOKEN",
            &secret,
        );

        let root_env_exists_after = root_env_path.exists();
        let profile_env_map = crate::server::profile_api::read_env_keys(
            &crate::server::profile_api::profile_dir_for("bot-profile").join(".env"),
        )
        .expect("parse profile .env");
        unsafe { std::env::remove_var("IRONHERMES_HOME") };

        let ack = result.expect("profile-scope write must succeed");
        assert_eq!(ack.key_name, "TELEGRAM_BOT_TOKEN");
        assert!(ack.present);
        assert!(
            !root_env_exists_after,
            "a profile-scope write must never create/touch the root .env"
        );
        assert_eq!(
            profile_env_map.get("TELEGRAM_BOT_TOKEN").map(String::as_str),
            Some("tg-bot-token")
        );
    }

