struct Fixture {
    tmp: tempfile::TempDir,
    paths: Tier2Paths,
    store: Store,
}

fn fixture() -> Fixture {
    let tmp = tempfile::tempdir().unwrap();
    let paths = Tier2Paths::from_home(tmp.path());
    paths.ensure_dirs().unwrap();
    let store = Store::open(&paths.db).unwrap();
    Fixture { tmp, paths, store }
}

impl Fixture {
    /// Insert an active, durable consolidation claim citing a live-log line.
    fn claim(&self, kind: &str, subject: &str, text: &str, line: usize) -> (i64, String) {
        let row = self
            .store
            .insert_claim(&NewClaim {
                text: text.into(),
                kind: kind.into(),
                subject: subject.into(),
                origin: "consolidation".into(),
                confidence: 0.9,
                source_url: Some(live_url(line)),
                tier1_target: None,
                tier1_ordinal: None,
                session_id: None,
            })
            .unwrap();
        (row.id, row.claim_id)
    }

    fn sql(&self, sql: &str, pk: i64) {
        rusqlite::Connection::open(&self.paths.db)
            .unwrap()
            .execute(sql, rusqlite::params![pk])
            .unwrap();
    }

    fn render(&self) {
        render_all(&self.store, &self.paths).unwrap();
    }

    /// Every file under the tier2 root as (relative path, bytes), sorted.
    fn snapshot(&self) -> Vec<(PathBuf, Vec<u8>)> {
        let mut out = Vec::new();
        walk(&self.paths.root, &self.paths.root, &mut out);
        out.sort();
        out
    }

    fn read(&self, rel: &str) -> String {
        std::fs::read_to_string(self.paths.root.join(rel)).unwrap()
    }
}

fn live_url(line: usize) -> String {
    format!("memory://live/2026-11-08.md#L{line}")
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<(PathBuf, Vec<u8>)>) {
    for e in std::fs::read_dir(dir).unwrap() {
        let p = e.unwrap().path();
        if p.is_dir() {
            walk(root, &p, out);
        } else {
            out.push((
                p.strip_prefix(root).unwrap().to_path_buf(),
                std::fs::read(&p).unwrap(),
            ));
        }
    }
}

fn derived_text(f: &Fixture) -> String {
    let mut all = String::new();
    for dir in [&f.paths.bank, &f.paths.people, &f.paths.groups] {
        for e in std::fs::read_dir(dir).unwrap() {
            all.push_str(&std::fs::read_to_string(e.unwrap().path()).unwrap());
        }
    }
    all
}

#[test]
fn render_bank_files_by_kind() {
    let f = fixture();
    let rows = [
        ("world", "world.md", "User lives in Vienna", 2),
        (
            "experience",
            "experience.md",
            "User visited Lisbon in May",
            3,
        ),
        ("opinion", "opinions.md", "User prefers concise replies", 4),
        (
            "reflection",
            "reflections.md",
            "User works best in mornings",
            5,
        ),
    ];
    let ids: Vec<String> = rows
        .iter()
        .map(|(kind, _, text, line)| f.claim(kind, "user", text, *line).1)
        .collect();
    f.render();
    for ((_, file, text, line), id) in rows.iter().zip(&ids) {
        let body = f.read(&format!("bank/{file}"));
        assert!(
            body.starts_with("# "),
            "{file} must start with a title: {body}"
        );
        assert!(body.contains(
            "<!-- generated by ironhermes Tier 2 from tier2.db; edits are overwritten -->"
        ));
        let expected = format!("- {text} [{id}] ({})", live_url(*line));
        assert!(
            body.lines().any(|l| l == expected),
            "{file} lacks line {expected:?}:\n{body}"
        );
        assert!(id.starts_with("claim:"));
    }
}

#[test]
fn render_excludes_tier1_superseded_staged_and_transient() {
    let f = fixture();
    f.claim("world", "user", "KEEP visible durable claim", 2);
    let t1 = f
        .store
        .insert_claim(&NewClaim {
            text: "TIER1 mirrored entry".into(),
            kind: "world".into(),
            subject: "user".into(),
            origin: "tier1".into(),
            confidence: 0.95,
            source_url: Some("memory://tier1/USER.md#L1".into()),
            tier1_target: Some("user".into()),
            tier1_ordinal: Some(1),
            session_id: None,
        })
        .unwrap();
    assert_eq!(t1.origin, "tier1");
    let (sup, _) = f.claim("world", "user", "SUPERSEDED old claim", 3);
    f.sql("UPDATE claims SET status = 'superseded' WHERE id = ?1", sup);
    let (staged, _) = f.claim("world", "user", "STAGED forget claim", 4);
    f.sql(
        "UPDATE claims SET status = 'staged_forget' WHERE id = ?1",
        staged,
    );
    let (transient, _) = f.claim("world", "user", "TRANSIENT claim", 5);
    f.sql("UPDATE claims SET durable = 0 WHERE id = ?1", transient);

    f.render();
    let all = derived_text(&f);
    assert!(all.contains("KEEP visible durable claim"));
    for gone in ["TIER1", "SUPERSEDED", "STAGED", "TRANSIENT"] {
        assert!(!all.contains(gone), "{gone} leaked into derived files");
    }
}

#[test]
fn render_people_and_groups_by_subject() {
    let f = fixture();
    let (_, pid) = f.claim("world", "person:Alex Smith", "Alex likes hiking", 2);
    let (_, gid) = f.claim(
        "experience",
        "group:Book Club!",
        "The club met on Friday",
        3,
    );
    f.claim("world", "user", "User owns a bike", 4);
    f.render();

    let person = f.read("people/alex-smith.md");
    assert!(person.contains(&format!("- Alex likes hiking [{pid}] ({})", live_url(2))));
    let group = f.read("groups/book-club.md");
    assert!(group.contains(&format!(
        "- The club met on Friday [{gid}] ({})",
        live_url(3)
    )));
    let bank = f.read("bank/world.md") + &f.read("bank/experience.md");
    assert!(bank.contains("User owns a bike"));
    assert!(
        !bank.contains("Alex likes hiking") && !bank.contains("The club met"),
        "person/group claims are not duplicated into the bank"
    );
}

#[test]
fn render_slug_rejects_traversal() {
    for good in ["alex-smith", "a", "0day", &"a".repeat(64)] {
        assert!(is_valid_slug(good), "{good} should be valid");
    }
    for bad in [
        "",
        "..",
        "a/b",
        "-a",
        "Alex",
        "a b",
        "a.md",
        &"a".repeat(65),
    ] {
        assert!(!is_valid_slug(bad), "{bad:?} should be invalid");
    }
    let long = "x".repeat(300);
    for name in ["../../etc", "/abs", "", long.as_str(), "..", "a/../b"] {
        let s = slugify(name);
        assert!(is_valid_slug(&s), "slugify({name:?}) = {s:?} is not valid");
    }
    assert_eq!(slugify(""), "unknown");
    assert_eq!(slugify("../../etc"), "etc");
    assert_eq!(slugify("Alex  Smith"), "alex-smith");

    let f = fixture();
    f.claim("world", "person:../../etc", "Traversal person", 2);
    f.claim("world", "group:/abs", "Traversal group", 3);
    f.claim("world", "person:", "Nameless person", 4);
    f.claim("world", &format!("person:{long}"), "Long-named person", 5);
    f.render();

    let root = f.paths.root.canonicalize().unwrap();
    for dir in [&f.paths.people, &f.paths.groups] {
        let canon_dir = dir.canonicalize().unwrap();
        let mut n = 0;
        for e in std::fs::read_dir(dir).unwrap() {
            let p = e.unwrap().path().canonicalize().unwrap();
            assert!(
                p.starts_with(&canon_dir),
                "{} escaped {}",
                p.display(),
                canon_dir.display()
            );
            n += 1;
        }
        assert!(n > 0, "{} should hold the sanitized files", dir.display());
    }
    // Nothing was written anywhere but under the tier2 root.
    let home = f.tmp.path().canonicalize().unwrap();
    for e in std::fs::read_dir(&home).unwrap() {
        let p = e.unwrap().path().canonicalize().unwrap();
        assert!(
            p == root || p.file_name().unwrap() == "state.db",
            "stray {}",
            p.display()
        );
    }
    assert!(f.paths.people.join("etc.md").is_file());
    assert!(f.paths.groups.join("abs.md").is_file());
    assert!(f.paths.people.join("unknown.md").is_file());
}

#[test]
fn render_is_wholesale_and_atomic() {
    let f = fixture();
    f.claim("world", "user", "User owns a bike", 2);
    let (pk, _) = f.claim("world", "person:Sam", "Sam is a cousin", 3);
    f.render();
    assert!(f.paths.people.join("sam.md").is_file());

    // Unchanged claims render byte-identical files and leave no temp file behind.
    let before = f.snapshot();
    f.render();
    assert_eq!(before, f.snapshot());
    assert!(
        f.snapshot()
            .iter()
            .all(|(p, _)| p.extension().is_none_or(|e| e != "tmp")),
        "a .tmp file remained"
    );

    // Removing the last claim of a person deletes that person's file.
    f.store.delete_claims(&[pk]).unwrap();
    f.render();
    assert!(!f.paths.people.join("sam.md").exists());
    assert!(f.read("bank/world.md").contains("User owns a bike"));
}

// G-58.2-3: a render in another process holding render.lock must make this one wait.
#[test]
fn render_waits_for_cross_process_lock() {
    use std::time::Duration;
    let f = fixture();
    f.claim("world", "user", "User owns a bike", 2);
    let held = std::fs::OpenOptions::new()
        .create(true)
        .write(true)
        .truncate(false)
        .open(
            f.paths
                .root
                .join(ironhermes_tier2::render::RENDER_LOCK_FILE),
        )
        .unwrap();
    held.lock().unwrap();

    let (tx, rx) = std::sync::mpsc::channel();
    std::thread::scope(|s| {
        s.spawn(|| {
            let store = Store::open(&f.paths.db).unwrap();
            let r = render_all(&store, &f.paths);
            tx.send(r.map(|_| ()).map_err(|e| format!("{e:#}")))
                .unwrap();
        });
        assert!(rx.recv_timeout(Duration::from_millis(300)).is_err());
        drop(held);
        rx.recv_timeout(Duration::from_secs(5))
            .expect("render returns once the lock is free")
            .unwrap();
    });
    assert!(f.read("bank/world.md").contains("User owns a bike"));
}

// G-58.2-3: overlapping renders must never fail (ENOENT on a shared temp name) or leave temp files.
#[test]
fn render_concurrent_runs_never_fail() {
    let f = fixture();
    f.claim("world", "user", "User owns a bike", 2);
    f.claim("world", "person:Sam", "Sam is a cousin", 3);
    f.claim("world", "person:Ana", "Ana is a neighbour", 4);
    std::thread::scope(|s| {
        for _ in 0..2 {
            s.spawn(|| {
                let store = Store::open(&f.paths.db).unwrap();
                for _ in 0..25 {
                    render_all(&store, &f.paths).unwrap();
                }
            });
        }
    });
    assert!(
        f.snapshot()
            .iter()
            .all(|(p, _)| p.extension().is_none_or(|e| e != "tmp")),
        "a .tmp file remained"
    );
    let before = f.snapshot();
    f.render();
    assert_eq!(before, f.snapshot());
}

#[tokio::test]
async fn render_runs_after_consolidation() {
    let tmp = tempfile::tempdir().unwrap();
    let mut state = StateStore::new(tmp.path().join("state.db")).unwrap();
    state
        .create_session("s1", "cli", None, None, None, None)
        .unwrap();
    let id = state
        .add_message(
            "s1",
            &ChatMessage::user("I prefer concise replies on mobile"),
        )
        .unwrap();
    let reply = json!({"claims": [{"text": "User prefers concise replies on mobile",
        "kind": "opinion", "subject": "user", "direct": true, "durable": true,
        "message_ids": [id]}]})
    .to_string();
    let cfg = MemoryConfig {
        consolidation_enabled: true,
        ..MemoryConfig::default()
    };
    let svc = Tier2Service::open_with_embedder(
        tmp.path(),
        &cfg,
        Embedder::Fake(FakeEmbedder::new("fake:a")),
    )
    .unwrap()
    .with_llm(Arc::new(FakeLlm::new(vec![Ok(reply)])));

    let report = svc.consolidate_now().await.unwrap();
    assert_eq!(report.claims_added, 1);
    let claim = svc.store().list_recent(10).unwrap().remove(0);
    let body = std::fs::read_to_string(tmp.path().join("tier2/bank/opinions.md")).unwrap();
    assert!(body.contains(&format!("[{}]", claim.claim_id)), "{body}");
    assert!(body.contains("memory://live/"), "{body}");
}
